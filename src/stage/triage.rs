    /// A file with `count` hunks of `added` added lines each, numbered so the
    /// two line sets stay believable.
    fn file(path: &str, hunks: usize, added: u32) -> FileChange {
        let mut change = FileChange {
            old_path: path.to_string(),
            new_path: path.to_string(),
            hunks: Vec::new(),
            commentable_lines: BTreeSet::new(),
            changed_lines: BTreeSet::new(),
            binary: false,
        };
        for index in 0..hunks {
            let start = 1 + index as u32 * 100;
            let mut text = format!("@@ -{start},1 +{start},{} @@\n", added + 1);
            for offset in 0..added {
                let line = start + offset;
                text.push_str(&format!("+int added_{line}(void);\n"));
                change.commentable_lines.insert(line);
                change.changed_lines.insert(line);
            }
            text.push_str(" int tail(void);\n");
            change.commentable_lines.insert(start + added);
            change.hunks.push(Hunk {
                old_start: start,
                old_count: 1,
                new_start: start,
                new_count: added + 1,
                text,
            });
        }
        change
    }

