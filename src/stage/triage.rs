//! Stage 2. Drop the noise, sort by how much changed, cut one chunk per file.
//!
//! One chunk is one file, always: two small files are never packed together,
//! and only a file that does not fit on its own is cut again along its hunk
//! boundaries.

use globset::{Glob, GlobSet, GlobSetBuilder};
use serde::{Deserialize, Serialize};

use crate::budget::{estimate_ascii_tokens, estimate_tokens};
use crate::config::{Config, ConfigError, Model, PROMPT_SKELETON_TOKENS, TriageSettings};
use crate::domain::{ChangeSet, DEV_NULL, FileChange};
use crate::security::PathPolicy;
use crate::tool::Registry;

use super::{StageContext, StageError};

pub const NUMBER: u8 = 2;
pub const NAME: &str = "triage";

/// Slack on top of the character based token estimate, which is conservative
/// but not exact. One reserve for the whole formula rather than a fudge
/// factor hidden in each term.
const HEADROOM_TOKENS: u32 = 1_024;

/// Below this a chunk cannot hold a file header, one hunk and the lines the
/// model has to quote back as evidence, so every real file would fail as too
/// large. A config that leaves less than this is wrong, not merely tight.
const MIN_CHUNK_TOKENS: u32 = 2_000;

/// Markers a generator leaves behind. Both spellings are conventions, not
/// standards, so they are matched anywhere in the file's diff text.
const GENERATED_MARKERS: [&str; 2] = ["@generated", "Code generated by"];

/// One chunk is one file, or one piece of a file too big to fit in a single
/// turn. Two files are never packed together, however small.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct Chunk {
    pub index: usize,
    pub path: String,
    /// Which piece of its file this is, counting from zero, and how many
    /// pieces that file was cut into. `pieces == 1` is the ordinary case.
    /// Both are needed downstream: the pieces of one file must not share a
    /// `trace_id`, and a model reading piece three has to be told the earlier
    /// hunks exist rather than concluding they do not.
    #[serde(default)]
    pub piece: usize,
    #[serde(default = "one_piece")]
    pub pieces: usize,
    pub diff: String,
}

impl Chunk {
    /// True when this file was cut, so the model is looking at part of it.
    pub fn is_split(&self) -> bool {
        self.pieces > 1
    }
}

fn one_piece() -> usize {
    1
}

/// A file that will not be reviewed, and why. Goes into the report.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
pub struct SkippedFile {
    pub path: String,
    pub reason: String,
}

#[derive(Clone, Debug, Default, Deserialize, PartialEq, Serialize)]
pub struct TriagePlan {
    pub chunks: Vec<Chunk>,
    pub skipped: Vec<SkippedFile>,
}

/// How many tokens of diff one chunk may carry.
///
/// The hard ceiling is whatever still fits in the window:
///
/// `context_window_tokens − max_output_tokens − prompt skeleton − tool allowance − headroom`
///
/// The working size is `[triage].max_chunk_tokens`, clamped down to that
/// ceiling. It has no builtin default: the leftover window is not itself a
/// useful review turn, and how much diff is worth one call depends on the
/// model and the project.
#[derive(Clone, Copy, Debug)]
pub struct ChunkLimit {
    tokens: u32,
}

impl ChunkLimit {
    /// `prompt_tokens` is measured from the assembled instructions and the
    /// tool schemas, not guessed: `PROMPT_SKELETON_TOKENS` is only the floor
    /// the startup check uses, before there is a registry to measure. It
    /// still floors this, so a prompt that somehow measures smaller than the
    /// startup check assumed cannot buy back window the check already gave
    /// away.
    pub fn new(
        model: &Model,
        config: &Config,
        tools: &Registry,
        prompt_tokens: u32,
    ) -> Result<Self, ConfigError> {
        let allowance = Self::tool_allowance(config, tools);
        let reserved = model
            .max_output_tokens
            .saturating_add(prompt_tokens.max(PROMPT_SKELETON_TOKENS))
            .saturating_add(allowance)
            .saturating_add(HEADROOM_TOKENS);
        let fit = model.context_window_tokens.saturating_sub(reserved);
        // The allowance is the one term a config can raise without noticing
        // what it costs: rounds times output bytes grows fast enough to eat a
        // small window whole. Say so here, where the registry is known, rather
        // than letting every file fail as too large.
        if allowance > 0 && fit < MIN_CHUNK_TOKENS {
            return Err(ConfigError::ToolAllowanceTooLarge {
                model: model.name.clone(),
                context_window_tokens: model.context_window_tokens,
                rounds: config.review.max_tool_rounds,
                allowance,
                left: fit,
            });
        }
        Ok(Self {
            tokens: fit.min(config.triage.max_chunk_tokens),
        })
    }

    pub fn tokens(self) -> u32 {
        self.tokens
    }

    /// What the tool loop may append to `input` before the last round.
    /// Delivery-only tools do not grow the conversation with bulk output, so
    /// they do not reserve this. Neither does one this run's worktree cannot
    /// answer: it is offered to the model like the rest, but all it can ever
    /// return is a one-line refusal.
    fn tool_allowance(config: &Config, tools: &Registry) -> u32 {
        let investigates = tools
            .offered_on(crate::tool::Round::Investigation)
            .iter()
            .any(|tool| {
                tool.purpose() != crate::tool::Purpose::Delivery && tool.unavailable().is_none()
            });
        if !investigates {
            return 0;
        }
        estimate_ascii_tokens(config.review.max_tool_output_bytes)
            .saturating_mul(config.review.max_tool_rounds)
    }
}

/// The skip rules, built once per run. `deny_paths` is not in here: that one
/// is `security`'s hard boundary, and this type only owns the cost policy.
pub struct FileFilter {
    skip_paths: GlobSet,
    skip_generated: bool,
    skip_files_over_bytes: u64,
}

impl FileFilter {
    pub fn new(triage: &TriageSettings) -> Result<Self, ConfigError> {
        let mut builder = GlobSetBuilder::new();
        for pattern in &triage.skip_paths {
            builder.add(
                Glob::new(pattern).map_err(|error| ConfigError::InvalidGlob {
                    field: "[triage].skip_paths",
                    pattern: pattern.clone(),
                    reason: error.to_string(),
                })?,
            );
        }
        Ok(Self {
            skip_paths: builder.build().map_err(|error| ConfigError::InvalidGlob {
                field: "[triage].skip_paths",
                pattern: String::new(),
                reason: error.to_string(),
            })?,
            skip_generated: triage.skip_generated,
            skip_files_over_bytes: triage.skip_files_over_bytes,
        })
    }

    /// Why this file is not reviewed, or `None` when it is. `deny_paths`
    /// comes first: it is the one rule the config cannot take away, and a
    /// file that lands on it is skipped even though the diff carries it.
    pub fn reason(&self, file: &FileChange, paths: &PathPolicy) -> Option<String> {
        let diff = FileDiff::new(file);
        if paths.is_denied(&file.new_path) || paths.is_denied(&file.old_path) {
            return Some("denied by deny_paths".to_string());
        }
        if self.skip_paths.is_match(&file.new_path) {
            return Some("matches [triage].skip_paths".to_string());
        }
        if file.binary {
            return Some("binary".to_string());
        }
        if file.new_path == DEV_NULL {
            return Some("the whole file was deleted".to_string());
        }
        if file.hunks.is_empty() {
            return Some("no reviewable lines in the diff".to_string());
        }
        if self.skip_generated && diff.contains_any(&GENERATED_MARKERS) {
            return Some("generated".to_string());
        }
        let size = diff.new_side_bytes();
        if size > self.skip_files_over_bytes {
            return Some(format!(
                "larger than [triage].skip_files_over_bytes ({size} > {})",
                self.skip_files_over_bytes
            ));
        }
        None
    }
}

/// One file's diff, rebuilt from the change set. Every piece it hands out is
/// a unified diff fragment of its own, headers included, so a later stage
/// still knows which file it is looking at.
struct FileDiff<'a> {
    file: &'a FileChange,
}

impl<'a> FileDiff<'a> {
    fn new(file: &'a FileChange) -> Self {
        Self { file }
    }

    fn header(&self) -> String {
        format!(
            "--- {}\n+++ {}\n",
            Self::side("a", &self.file.old_path),
            Self::side("b", &self.file.new_path)
        )
    }

    fn side(prefix: &str, path: &str) -> String {
        match path {
            DEV_NULL => DEV_NULL.to_string(),
            path => format!("{prefix}/{path}"),
        }
    }

    /// The path a report should name. A deleted file has no new side, so it
    /// is named by the one it had.
    fn display_path(&self) -> String {
        match self.file.new_path.as_str() {
            DEV_NULL | "" => self.file.old_path.clone(),
            path => path.to_string(),
        }
    }

    fn whole(&self) -> String {
        let mut text = self.header();
        for hunk in &self.file.hunks {
            text.push_str(&hunk.text);
        }
        text
    }

    fn contains_any(&self, markers: &[&str]) -> bool {
        self.file
            .hunks
            .iter()
            .any(|hunk| markers.iter().any(|marker| hunk.text.contains(marker)))
    }

    /// The new file's size as far as the diff shows it: the lines that
    /// survive on the new side, which are the added and context ones.
    fn new_side_bytes(&self) -> u64 {
        self.file
            .hunks
            .iter()
            .flat_map(|hunk| hunk.text.lines())
            .filter(|line| line.starts_with('+') || line.starts_with(' '))
            .map(|line| line.len() as u64)
            .sum()
    }

    /// One piece while the file fits, otherwise as few pieces as the hunk
    /// boundaries allow. A single hunk over the limit still gets a piece to
    /// itself: cutting inside a hunk would hand the model a broken diff.
    fn pieces(&self, limit: u32) -> Vec<String> {
        let whole = self.whole();
        if estimate_tokens(&whole) <= limit {
            return vec![whole];
        }
        let header = self.header();
        let header_tokens = estimate_tokens(&header);
        let mut pieces = Vec::new();
        let mut body = String::new();
        let mut tokens = header_tokens;
        for hunk in &self.file.hunks {
            let cost = estimate_tokens(&hunk.text);
            if !body.is_empty() && tokens.saturating_add(cost) > limit {
                pieces.push(format!("{header}{body}"));
                body.clear();
                tokens = header_tokens;
            }
            body.push_str(&hunk.text);
            tokens = tokens.saturating_add(cost);
        }
        if !body.is_empty() {
            pieces.push(format!("{header}{body}"));
        }
        pieces
    }
}

pub struct Triage;

impl Triage {
    pub fn run(
        context: &mut StageContext<'_>,
        changeset: &ChangeSet,
        prompt_tokens: u32,
    ) -> Result<TriagePlan, StageError> {
        let model = context.settings.selection()?.model;
        let limit = ChunkLimit::new(
            model,
            &context.settings.config,
            &context.adapters.tools,
            prompt_tokens,
        )?;
        let filter = FileFilter::new(&context.settings.config.triage)?;
        let plan = Self::plan(changeset, &filter, context.paths, limit);

        for file in &plan.skipped {
            tracing::debug!(path = %file.path, reason = %file.reason, "file skipped");
        }
        tracing::info!(
            chunks = plan.chunks.len(),
            skipped = plan.skipped.len(),
            chunk_limit = limit.tokens(),
            prompt_tokens,
            "triage done"
        );
        context.complete(NUMBER, NAME, &plan)?;
        Ok(plan)
    }

    /// Filter, sort, cut. Everything it needs is in the arguments, so the
    /// algorithm is testable without a run directory or a model.
    fn plan(
        changeset: &ChangeSet,
        filter: &FileFilter,
        paths: &PathPolicy,
        limit: ChunkLimit,
    ) -> TriagePlan {
        let mut skipped = Vec::new();
        let mut reviewable: Vec<&FileChange> = Vec::new();
        for file in &changeset.files {
            match filter.reason(file, paths) {
                Some(reason) => skipped.push(SkippedFile {
                    path: FileDiff::new(file).display_path(),
                    reason,
                }),
                None => reviewable.push(file),
            }
        }

        // Most changed lines first. No path weighting: which directory is
        // worth more is a project policy, and `skip_paths` is where a user
        // says so. The path tie break only makes the order reproducible.
        reviewable.sort_by(|left, right| {
            right
                .changed_lines
                .len()
                .cmp(&left.changed_lines.len())
                .then_with(|| left.new_path.cmp(&right.new_path))
        });

        let mut chunks = Vec::new();
        for file in reviewable {
            let cut = FileDiff::new(file).pieces(limit.tokens());
            let pieces = cut.len();
            for (piece, diff) in cut.into_iter().enumerate() {
                chunks.push(Chunk {
                    index: chunks.len(),
                    path: file.new_path.clone(),
                    piece,
                    pieces,
                    diff,
                });
            }
        }
        TriagePlan { chunks, skipped }
    }
}

